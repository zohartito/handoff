test("autoCapture: fixture yields exactly 1 auto attempt + 1 auto correction, idempotent", async () => {
  const dir = scaffoldHandoff();
  const paths = resolveHandoffPaths(dir);
  const payload = { transcript_path: FIXTURE, session_id: "sess-auto-0001" };
  try {
    await autoCapture({ cwd: dir, payload });

    // Exactly one auto attempt, tagged, and it's the failing npm test with a fix.
    const attempts = readFileSync(paths.attempts, "utf8");
    assert.equal(attempts.split("**source:** auto").length - 1, 1, "one auto attempt");
    assert.match(attempts, /\*\*tried:\*\* npm test/);
    assert.match(attempts, /\*\*fix:\*\* later succeeded/);

    // Exactly one auto correction, tagged, capturing the pathlib feedback.
    const corrections = readFileSync(paths.corrections, "utf8");
    assert.equal(corrections.split("**source:** auto").length - 1, 1, "one auto correction");
    assert.match(corrections, /\*\*user said:\*\* no, use pathlib not os\.path/);
    assert.match(corrections, /\*\*agent did:\*\*/);

    // decisions.md untouched, no transcript written.
    assert.equal(existsSync(paths.decisions), false, "decisions.md untouched");
    assert.equal(existsSync(paths.transcript), false, "no transcript.jsonl written");
    assert.equal(existsSync(join(dir, ".handoff", "transcript.md")), false, "no transcript.md written");

    // Sidecar records the cursor and the two entry hashes.
    const state = JSON.parse(readFileSync(paths.captureState, "utf8"));
    assert.equal(state.version, 1);
    assert.ok(state.sessions["sess-auto-0001"].lastLineProcessed > 0, "cursor advanced");
    assert.equal(state.seenHashes.length, 2, "two hashes remembered");

    // Re-running appends nothing.
    const before = readFileSync(paths.attempts, "utf8") + readFileSync(paths.corrections, "utf8");
    await autoCapture({ cwd: dir, payload });
    const after = readFileSync(paths.attempts, "utf8") + readFileSync(paths.corrections, "utf8");
    assert.equal(after, before, "second run is a no-op");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("a user correction delivered as content blocks is captured", async () => {
  // Claude Code sends user messages either as a bare string or as content
  // blocks (pasted attachments, multi-part input). Only the string form was
  // read, so a real correction in block form was invisible to auto-capture.
  const { parseSessionEvents } = await import("../src/commands/ingest.js");
  const { detectCorrections } = await import("../src/commands/auto-capture.js");
  const { mkdtempSync, writeFileSync } = await import("node:fs");
  const { tmpdir } = await import("node:os");
  const { join } = await import("node:path");

  const dir = mkdtempSync(join(tmpdir(), "handoff-blockform-"));
  const file = join(dir, "s.jsonl");
  const cwd = "/proj";
  writeFileSync(
    file,
    [
      { type: "user", timestamp: "2026-08-01T10:00:00Z", cwd, sessionId: "s", message: { role: "user", content: [{ type: "text", text: "Build the importer." }] } },
      { type: "assistant", timestamp: "2026-08-01T10:01:00Z", cwd, sessionId: "s", message: { role: "assistant", content: [{ type: "tool_use", name: "Edit", id: "t1", input: { file_path: "a.py" } }] } },
      { type: "user", timestamp: "2026-08-01T10:02:00Z", cwd, sessionId: "s", message: { role: "user", content: [{ type: "text", text: "no, don't use os.path here — always prefer pathlib" }] } },
    ]
      .map((o) => JSON.stringify(o))
      .join("\n") + "\n",
  );

  const session = await parseSessionEvents(file);
  const found = detectCorrections(session);
  assert.equal(found.length, 1, "block-form correction should be detected");
  assert.match(found[0]!.userSaid, /prefer pathlib/);
});

test("HOF-22: automatic capture redacts credentials before persistence and priming", async () => {
  const { buildPrimer } = await import("../src/commands/prime.js");
  const root = scaffoldHandoff();
  const marker = "synthetic-audit-value-" + "123456";
  const transcript = join(root, "session.jsonl");
  const command = `NPM_TOKEN='${marker}' npm run build --password=${marker}`;
  const error = `Error Authorization: Bearer ${marker}\n{"api_key":"${marker}"}\nhttps://synthetic:${marker}@example.invalid/fail`;
  writeFileSync(transcript, failingBashJsonl(command, error));
  await autoCapture({ cwd: root, payload: { transcript_path: transcript, session_id: "audit-redaction" } });
  const paths = resolveHandoffPaths(root);
  const saved = readFileSync(paths.attempts, "utf8");
  assert.ok(!saved.includes(marker), "no synthetic credential may persist");
  assert.match(saved, /\[REDACTED\]/);
  assert.match(saved, /npm run build/);
  const primer = await buildPrimer(paths, "generic", Infinity);
  assert.ok(!primer.includes(marker), "primers must not disclose captured credentials");
  // Explicit manual logging remains verbatim, not an implicit raw hook capture.
  await attempt({ cwd: root, what: "manual diagnostic", error: "literal diagnostic", quiet: true });
  assert.match(readFileSync(paths.attempts, "utf8"), /literal diagnostic/);
});
